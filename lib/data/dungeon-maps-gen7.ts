// Gen 7 dungeon maps — schematic layouts for the story dungeons of
// Pokémon Sun & Moon and Pokémon Ultra Sun & Ultra Moon.
// Grids are readable approximations, not pixel-perfect maps; item
// lists were researched from Bulbapedia and GameFAQs/Thonky walkthroughs.
// Coordinates are 0-indexed (x = column, y = row) and match the grid:
// '#' wall, '.' walkable, 'S' stairs/ladder, 'I' item, 'T' trainer,
// 'E' entrance, 'X' exit. Hidden items are marked "(hidden)" in the name.

export interface DungeonMapItem { x: number; y: number; name: string }
export interface DungeonMapTrainer { x: number; y: number; note: string }
export interface DungeonFloor {
  name: string;            // "1F", "B1F"
  grid: string[];          // rows of chars; '#' wall, '.' walkable, 'S' stairs/ladder, 'I' item, 'T' trainer, 'E' entrance, 'X' exit
  items: DungeonMapItem[];
  trainers: DungeonMapTrainer[];
  notes?: string;
}
export interface DungeonMap {
  game: string;
  dungeon: string;
  floors: DungeonFloor[];  // in traversal order
  walkthrough: string[];   // numbered steps in traversal order; item pickups and trainer battles inline
}

