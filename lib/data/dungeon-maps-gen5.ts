/**
 * Gen 5 (Unova) story-dungeon maps for Pokémon Companion.
 *
 * Schematic walkthrough maps — readable approximations, not pixel-perfect.
 * Grid legend: '#' wall, '.' walkable, 'S' stairs/ladder, 'I' item,
 * 'T' trainer, 'E' entrance, 'X' exit. Coordinates are 0-indexed
 * (x = column, y = row) and match the grid rows.
 *
 * Item locations researched from Bulbapedia dungeon pages (Oct 2026).
 */
export interface DungeonMapItem {
  x: number;
  y: number;
  name: string;
}

export interface DungeonMapTrainer {
  x: number;
  y: number;
  note: string;
}

export interface DungeonFloor {
  name: string; // "1F", "B1F", ...
  grid: string[]; // rows of chars
  items: DungeonMapItem[];
  trainers: DungeonMapTrainer[];
  notes?: string;
}

